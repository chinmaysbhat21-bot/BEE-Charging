import { chromium, expect } from '@playwright/test'
import { createServer } from 'vite'
import { mkdir } from 'node:fs/promises'
import { startFixture } from '../../backend/tests/uiFixture.js'
import Consumer from '../../backend/models/consumer.js'
let fixture, vite, browser
try {
  fixture = await startFixture()
  const consumer = await Consumer.findOne({ email: 'driver@example.test' })
  consumer.batteries[0].maxAcChargingPowerKw = 7
  await consumer.save()
  vite = await createServer({ server: { host: '127.0.0.1', port: 0, proxy: { '/api': { target: `http://127.0.0.1:${fixture.port}` } } } })
  await vite.listen()
  const baseURL = `http://127.0.0.1:${vite.httpServer.address().port}`
  browser = await chromium.launch()
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const errors = []; page.on('pageerror', (err) => errors.push(err.message))
  await mkdir('test-results/charging-points', { recursive: true })
  async function login(email) {
    await context.clearCookies()
    const { otp } = await (await context.request.post('/api/consumer/auth/login/request-otp', { data: { email } })).json()
    expect((await context.request.post('/api/consumer/auth/login/verify-otp', { data: { email, otp } })).ok()).toBeTruthy()
    await page.goto(baseURL)
    await expect(page.getByRole('button', { name: 'Open menu' })).toBeVisible()
  }
  await login('host@example.test')
  await page.getByRole('button', { name: 'Open menu' }).click()
  await page.getByRole('navigation', { name: 'More options' }).getByRole('button', { name: 'Host', exact: true }).click()
  await page.getByRole('button', { name: '+ Add Charging Station', exact: true }).click()
  const form = page.locator('.host-station-form')
  await form.getByLabel('Station Name *', { exact: true }).fill('Browser Multi Hub')
  await form.getByLabel('Address *', { exact: true }).fill('Test street')
  await form.getByLabel('Area *', { exact: true }).fill('Test area')
  await form.getByLabel('City *', { exact: true }).fill('Mangalore')
  await form.getByLabel('State *', { exact: true }).fill('Karnataka')
  await form.getByLabel('PIN Code *', { exact: true }).fill('575001')
  await form.getByLabel('Latitude', { exact: true }).fill('12.9')
  await form.getByLabel('Longitude', { exact: true }).fill('74.85')
  await form.getByRole('radio', { name: /Other/ }).check()
  await form.getByLabel('Other network name').fill('Neighbourhood Network')
  await form.getByRole('button', { name: '+ Add Charging Point', exact: true }).click()
  await form.getByRole('button', { name: '+ Add Charging Point', exact: true }).click()
  const cards = form.locator('.point-editor-card')
  await cards.nth(1).getByLabel('Price per kWh (INR)').fill('18')
  await cards.nth(2).getByRole('button', { name: /Electric Bike/ }).click()
  await cards.nth(2).getByLabel('Exact connector names').fill('3-pin 230V AC (own OEM charger)')
  await expect(form.getByText(/Supported models and battery specifications/)).toHaveCount(0)
  await expect(form.getByLabel('Supported model', { exact: true })).toHaveCount(0)
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await cards.nth(2).screenshot({ path: `test-results/charging-points/bike-${width}.png` })
    await form.locator('.network-options').screenshot({ path: `test-results/charging-points/networks-${width}.png` })
  }
  await form.getByRole('button', { name: 'Save charging station' }).click()
  await expect(page.getByRole('heading', { name: 'Browser Multi Hub' })).toBeVisible()
  const stationCard = page.locator('.host-station-card').filter({ has: page.getByRole('heading', { name: 'Browser Multi Hub' }) })
  await expect(stationCard.getByText('3 charging points · 2 car · 1 bike')).toBeVisible()
  await stationCard.getByRole('button', { name: 'Manage charging points' }).click()
  await stationCard.getByRole('button', { name: '+ Add Charging Point', exact: true }).click()
  await stationCard.locator('.point-editor-card').last().getByRole('button', { name: 'Remove charging point', exact: true }).click()
  await stationCard.getByRole('button', { name: 'Save charging points', exact: true }).click()
  await expect(stationCard.getByText('Charging points saved.', { exact: true })).toBeVisible()
  const stations = (await (await context.request.get('/api/charging-stations')).json()).stations
  const station = stations.find((s) => s.name === 'Browser Multi Hub')
  expect(stations.filter((s) => s._id === station._id)).toHaveLength(1)
  expect(station.chargers[2].supportedVehicles).toHaveLength(0)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await login('driver@example.test')
  await page.evaluate(({ id, batteryId }) => localStorage.setItem(`communityEvCharging.bookingSelections.${id}`, JSON.stringify({ address: { id: 'current-location', nickname: 'Current Location', latitude: 12.9, longitude: 74.85, city: 'Mangalore' }, battery: { id: batteryId }, initialCharge: 20, finalCharge: 30 })), { id: consumer.id, batteryId: consumer.batteries[0].id })
  await page.reload()
  await page.getByRole('button', { name: 'Find stations', exact: true }).click()
  const nextDay = new Date(Date.now() + 86400000)
  const date = `${nextDay.getFullYear()}-${String(nextDay.getMonth() + 1).padStart(2, '0')}-${String(nextDay.getDate()).padStart(2, '0')}`
  await page.getByLabel('Choose charging date').fill(date)
  await page.getByLabel('Filter stations by vehicle category').selectOption('car')
  await page.setViewportSize({ width: 390, height: 900 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.setViewportSize({ width: 1440, height: 1000 })
  const stationListing = page.locator('.charging-station-card').filter({ has: page.getByRole('heading', { name: 'Browser Multi Hub' }) })
  await stationListing.getByRole('button', { name: 'View Details' }).click()
  const selector = page.getByLabel('Choose a compatible charging point')
  await expect(selector.locator('option')).toHaveCount(2)
  await selector.selectOption(station.chargers[1]._id)
  await expect(selector).toHaveValue(station.chargers[1]._id)
  await page.setViewportSize({ width: 390, height: 900 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/charging-points/consumer-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.locator('.station-time-slot-list button').first().click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  page.on('dialog', (dialog) => dialog.accept())
  const booked = page.waitForResponse((r) => r.url().endsWith('/api/bookings') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Book', exact: true }).click()
  const bookingResponse = await booked
  expect(bookingResponse.status()).toBe(201)
  expect((await bookingResponse.json()).booking.chargingPointId).toBe(station.chargers[1]._id)
  expect(errors).toEqual([])
  console.log('PASS host mixed-point creation/edit, network Other, car/bike forms without supported-model options, mobile/tablet/desktop layouts and consumer point selection and reservation.')
} finally { await browser?.close(); await vite?.close(); await fixture?.close() }
